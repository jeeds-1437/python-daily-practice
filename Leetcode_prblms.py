#NUMBERS - SQUARE PATTERN
'''for i in range(1,5):
    for j in range(1,5):
        print(i,end=' ')
    print(end='\n')'''

#INCREASING STAR TRIANGLE
'''for i in range(1,5):
    for j in range(1,i+1):
        print('*',end=' ')
    print('\n')'''

#DECREASING STAR TRIANGLE
'''for i in range(5,0,-1):
    for j in range(i):
        print('*',end=' ')
    print()'''

#NUMBERS - INVERTED PATTERN
'''for i in range(1,5):
    for j in range(1,i+1):
        print(j,end=' ')
    print()'''

#HORIZONTAL NUMBERS
'''for i in range(1,5):
    for j in range(1,5):
        print(j,end=' ')
    print()'''

#CONTINUOUS NUMBERS
